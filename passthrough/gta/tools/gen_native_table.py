#!/usr/bin/env python3
"""Cross-checks shv/native_hashes.h against the FiveM natives reference and emits tests/native_signatures.inc.

Usage:
    curl -sSL -o natives.json https://runtime.fivem.net/doc/natives.json
    python3 tools/gen_native_table.py natives.json > tests/native_signatures.inc

For every `inline constexpr uint64_t NAME = 0x...;` in native_hashes.h the script looks the hash up in the reference,
fails loudly if it is missing or if the name differs, and records the documented parameter count. The Linux test
(tests/test_natives.cpp) then fails if natives.cpp ever calls a hash with a different number of arguments.

Two deliberate deviations are listed in OVERRIDES: SET_OBJECT_TEXTURE_VARIATION is documented under its legacy
underscore name, and END_TEXT_COMMAND_DISPLAY_TEXT is called with a trailing p2 that older SDK wrappers omit.
"""
import json
import re
import sys

ALIASES = {"SET_OBJECT_TEXTURE_VARIATION": "_SET_OBJECT_TEXTURE_VARIATION"}
# name -> argument count the mod passes, where it intentionally differs from the (older) documented count.
OVERRIDES = {"END_TEXT_COMMAND_DISPLAY_TEXT": 3}


def main(path):
    ref = json.load(open(path))
    by_hash = {}
    for ns in ref.values():
        for h, n in ns.items():
            by_hash[int(h, 16)] = n
    header = open(__file__.replace("tools/gen_native_table.py", "src/shv/native_hashes.h")).read()
    rows = []
    bad = False
    for m in re.finditer(r"inline constexpr uint64_t (\w+) = (0x[0-9A-Fa-f]+);", header):
        name, h = m.group(1), int(m.group(2), 16)
        n = by_hash.get(h)
        if n is None:
            print(f"// ERROR: {name} {m.group(2)} not found in reference", file=sys.stderr)
            bad = True
            continue
        want = ALIASES.get(name, name)
        if n["name"] != want:
            print(f"// ERROR: {name}: reference calls {m.group(2)} {n['name']}", file=sys.stderr)
            bad = True
            continue
        params = len(n["params"])
        params = OVERRIDES.get(name, params)
        rows.append((name, m.group(2), params, n["results"]))
    if bad:
        sys.exit(1)
    print("// Generated by tools/gen_native_table.py from the FiveM natives reference. Do not edit.")
    for name, h, params, res in sorted(rows):
        print(f'{{"{name}", {h}ull, {params}, "{res}"}},')


if __name__ == "__main__":
    main(sys.argv[1])
